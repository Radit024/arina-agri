import { initializeApp, getApps } from 'firebase/app';
import { getAuth } from 'firebase/auth';

type RuntimeFirebaseConfig = {
  apiKey: string;
  authDomain: string;
  projectId: string;
  storageBucket: string;
  messagingSenderId: string;
  appId: string;
};

declare global {
  interface Window {
    __ARINA_FIREBASE_CONFIG__?: RuntimeFirebaseConfig;
  }
}

const fallbackConfig: RuntimeFirebaseConfig = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || 'mock-api-key',
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || 'mock.firebaseapp.com',
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || 'mock-project-id',
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || 'mock.appspot.com',
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || '123456789',
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || '1:123456789:web:abcdef',
};

const runtimeConfig = typeof window !== 'undefined' ? window.__ARINA_FIREBASE_CONFIG__ : undefined;
const firebaseConfig = runtimeConfig && runtimeConfig.apiKey ? runtimeConfig : fallbackConfig;

// Initialize Firebase only if it hasn't been initialized yet
const app = getApps().length === 0 ? initializeApp(firebaseConfig) : getApps()[0];
export const auth = getAuth(app);
